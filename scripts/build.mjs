import { createHash } from 'node:crypto';
import { lstat, mkdir, readFile, readdir, realpath, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { META_CSP } from './security.mjs';

export const PROJECT_ROOT = fileURLToPath(new URL('../', import.meta.url));
const ROOT_FILES = new Set(['index.html', 'blog.html', 'faq.html', '404.html', 'styles.css', 'game.js', 'robots.txt', 'sitemap.xml']);
const ASSET_TYPES = new Set(['.png', '.jpg', '.jpeg', '.webp', '.gif', '.avif', '.svg', '.ico', '.woff', '.woff2', '.css', '.js', '.mp4', '.webm', '.ogg', '.mp3']);
const MARKER = '.itchson-build';
const MARKER_CONTENT = 'Generated by scripts/build.mjs. Safe to rebuild.\n';

function allowedFile(relative) {
  return ROOT_FILES.has(relative) || relative === 'assets/fonts/OFL.txt' || (relative.startsWith('assets/') && ASSET_TYPES.has(path.posix.extname(relative)));
}

async function collect(directory, prefix = '') {
  const result = [];
  for (const entry of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    const relative = prefix + entry.name;
    if (!/^[a-zA-Z0-9][a-zA-Z0-9._-]*$/.test(entry.name)) throw new Error(`Disallowed source name: ${relative}`);
    if (entry.isSymbolicLink()) throw new Error(`Symlinks are not allowed: ${relative}`);
    if (entry.isDirectory()) {
      if (relative !== 'assets' && !relative.startsWith('assets/')) throw new Error(`Disallowed source directory: ${relative}`);
      result.push(...await collect(path.join(directory, entry.name), relative + '/'));
    } else if (entry.isFile() && allowedFile(relative)) {
      result.push({ relative, bytes: await readFile(path.join(directory, entry.name)) });
    } else {
      throw new Error(`Disallowed source file: ${relative}`);
    }
  }
  return result;
}

function validateActiveContent(relative, text) {
  if (relative.endsWith('.html')) {
    if (/<style\b|\sstyle\s*=|\son[a-z]+\s*=|(?:javascript|vbscript)\s*:/i.test(text)) throw new Error(`Inline active content is not allowed: ${relative}`);
    for (const match of text.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)) {
      const source = /\bsrc\s*=\s*(["'])([^"']+)\1/i.exec(match[1]);
      if (!source || match[2].trim() || /^(?:[a-z]+:|\/\/)/i.test(source[2])) throw new Error(`Scripts must be external, local files: ${relative}`);
    }
    for (const match of text.matchAll(/\bsrc\s*=\s*(["'])([^"']+)\1/gi)) {
      if (/^(?:[a-z]+:|\/\/)/i.test(match[2])) throw new Error(`External embedded content is not allowed: ${relative}`);
    }
    for (const match of text.matchAll(/<link\b[^>]*>/gi)) {
      const href = /\bhref\s*=\s*(["'])([^"']+)\1/i.exec(match[0]);
      const isCanonical = /\brel\s*=\s*(["'])canonical\1/i.test(match[0]);
      const isOwnCanonical = isCanonical && href && new URL(href[2], 'https://itchson.com').origin === 'https://itchson.com';
      if (href && /^(?:[a-z]+:|\/\/)/i.test(href[2]) && !isOwnCanonical) throw new Error(`External linked resources are not allowed: ${relative}`);
    }
    if (!/<head\b[^>]*>/i.test(text)) throw new Error(`HTML needs a head element: ${relative}`);
  }
  if (relative.endsWith('.svg') && /<script\b|<foreignObject\b|\son[a-z]+\s*=|(?:javascript|vbscript)\s*:|(?:href|src)\s*=\s*["']\s*(?:[a-z]+:|\/\/)/i.test(text)) {
    throw new Error(`Active or remote SVG content is not allowed: ${relative}`);
  }
}

function rewriteReferences(text, relative, names) {
  const rewrite = (value) => {
    if (/^(?:[a-z][a-z0-9+.-]*:|\/\/|#)/i.test(value)) return value;
    const url = new URL(value, `https://build.invalid/${relative}`);
    const replacement = names.get(decodeURIComponent(url.pathname.slice(1)));
    return replacement ? '/' + replacement + url.search + url.hash : value;
  };
  const replace = (match, prefix, quote, value) => {
    try { return prefix + quote + rewrite(value) + quote; } catch { return match; }
  };
  if (relative.endsWith('.html')) return text.replace(/(\b(?:href|src|poster)\s*=\s*)(["'])([^"'\r\n]+)\2/gi, replace);
  if (relative.endsWith('.css')) {
    text = text.replace(/(\burl\(\s*|@import\s+)(["'])([^"'\r\n]+)\2/gi, replace);
    return text.replace(/url\(\s*([^\s"')]+)\s*\)/gi, (match, value) => `url(${rewrite(value)})`);
  }
  if (relative.endsWith('.js')) {
    text = text.replace(/(\b(?:import|export)\s+(?:[^;'"`]+?\s+from\s*)?)(["'])([^"'\r\n]+)\2/g, replace);
    return text.replace(/(\bimport\s*\(\s*)(["'])([^"'\r\n]+)\2/g, replace);
  }
  return text;
}

async function checkExistingBuild(output) {
  let info;
  try { info = await lstat(output); } catch (error) { if (error.code === 'ENOENT') return; throw error; }
  if (info.isSymbolicLink() || !info.isDirectory()) throw new Error('Refusing to replace a non-directory or symlink at build/.');
  if ((await readdir(output)).length === 0) return;
  let marker;
  try { marker = await readFile(path.join(output, MARKER), 'utf8'); } catch { /* unrecognized directory */ }
  if (marker !== MARKER_CONTENT) throw new Error('Refusing to replace an unrecognized build/. Move it aside before building.');
  async function inspect(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      if (entry.isSymbolicLink()) throw new Error('Refusing to rebuild output containing symlinks.');
      if (entry.isDirectory()) await inspect(path.join(directory, entry.name));
    }
  }
  await inspect(output);
}

export async function build({ root = PROJECT_ROOT } = {}) {
  const workspace = await realpath(root);
  const source = path.join(workspace, 'site');
  const output = path.join(workspace, 'build');
  const sourceInfo = await lstat(source);
  if (!sourceInfo.isDirectory() || sourceInfo.isSymbolicLink()) throw new Error('site/ must be a real directory.');
  const files = await collect(source);
  if (!files.some((file) => file.relative === 'index.html')) throw new Error('site/index.html is required.');
  for (const file of files) validateActiveContent(file.relative, file.bytes.toString('utf8'));
  // Include all source bytes so a dependency change also invalidates referring CSS/JS.
  const digest = createHash('sha256');
  for (const file of files) digest.update(file.relative).update('\0').update(file.bytes).update('\0');
  const fingerprint = digest.digest('hex').slice(0, 16);
  const names = new Map(files.map(({ relative }) => [relative, relative.replace(/\.(css|js)$/, `.${fingerprint}.$1`)]));
  const rendered = files.map(({ relative, bytes }) => {
    if (/\.(html|css|js)$/.test(relative)) {
      let text = rewriteReferences(bytes.toString('utf8'), relative, names);
      if (relative.endsWith('.html')) {
        // A meta policy protects S3-only hosting too; CloudFront adds header-only protections.
        text = text.replace(/<meta\b[^>]*http-equiv\s*=\s*["']Content-Security-Policy["'][^>]*>/gi, '');
        text = text.replace(/<head\b[^>]*>/i, (head) => `${head}\n  <meta http-equiv="Content-Security-Policy" content="${META_CSP}">`);
      }
      bytes = Buffer.from(text);
    }
    return { relative: names.get(relative), bytes };
  });
  await checkExistingBuild(output);
  // output is a fixed direct child of the resolved workspace, never user-supplied.
  if (path.dirname(output) !== workspace || path.basename(output) !== 'build') throw new Error('Unsafe output directory.');
  await rm(output, { recursive: true, force: true });
  await mkdir(output);
  await writeFile(path.join(output, MARKER), MARKER_CONTENT);
  for (const file of rendered) {
    const destination = path.join(output, ...file.relative.split('/'));
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, file.bytes);
  }
  return { output, files: rendered.map(({ relative }) => relative), fingerprint };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = await build();
    console.log(`Built ${result.files.length} static files in ${result.output}`);
  } catch (error) {
    console.error(`Build failed: ${error.message}`);
    process.exitCode = 1;
  }
}
